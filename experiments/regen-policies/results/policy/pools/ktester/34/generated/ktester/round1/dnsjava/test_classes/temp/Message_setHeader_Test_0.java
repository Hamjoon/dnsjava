package org.xbill.DNS;

import org.junit.jupiter.api.*;
import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import org.mockito.junit.jupiter.MockitoExtension;
import java.util.stream.Stream;

@ExtendWith(MockitoExtension.class)
class Message_setHeader_Test {

    private Message message;

    private Header header1;

    private Header header2;

    /**
     * Helper holder for a parameterised scenario.
     */
    private static final class HeaderScenario {

        final Header header;

        final BiConsumer<Message, Header> assertions;

        HeaderScenario(Header header, BiConsumer<Message, Header> assertions) {
            this.header = header;
            this.assertions = assertions;
        }

        void apply(Message msg) {
            msg.setHeader(header);
            assertions.accept(msg, header);
        }

        @Override
        public String toString() {
            return "HeaderScenario{" + (header == null ? "null" : "Header@" + System.identityHashCode(header)) + '}';
        }
    }

    @BeforeEach
    void setupBeforeEach() {
        // Fresh Message for each test
        message = new Message();
        // Two distinct Header instances with different IDs – used by several tests
        header1 = new Header(1234);
        header2 = new Header(5678);
    }

    @AfterEach
    void teardownAfterEach() {
        // Help the garbage collector – not strictly required
        message = null;
        header1 = null;
        header2 = null;
    }

    private static Stream<HeaderScenario> headerScenarios() {
        return Stream.of(// fresh header
        new HeaderScenario(new Header(), (msg, hdr) -> {
            assertSame(hdr, msg.getHeader(), "Fresh Header should be stored and returned unchanged");
        }), // null header – clears field
        new HeaderScenario(null, (msg, hdr) -> {
            assertNull(msg.getHeader(), "Header should be null after assigning null");
        }));
    }

    @Test
    void setHeader_replacesHeader_correctly() {
        // Initially the Message has a Header generated by its no‑arg constructor
        Header originalHeader = message.getHeader();
        assertNotNull(originalHeader, "Message should always have a non‑null Header");
        // Replace with header1 and verify
        message.setHeader(header1);
        assertSame(header1, message.getHeader(), "Message.getHeader() should return the Header set via setHeader");
        // Replace again with header2 and verify that the previous Header is no longer used
        message.setHeader(header2);
        assertSame(header2, message.getHeader(), "Subsequent calls to setHeader should replace the previous Header");
        assertNotSame(header1, message.getHeader(), "The earlier Header instance should no longer be referenced");
    }

    @Test
    void setHeader_affectsHeaderId() {
        // Set a known Header and check that its ID is reflected in the Message
        message.setHeader(header1);
        assertEquals(1234, message.getHeader().getID(), "Header ID should match the ID of the Header supplied to setHeader");
        // Change to another Header and verify the ID changes accordingly
        message.setHeader(header2);
        assertEquals(5678, message.getHeader().getID(), "Header ID should be updated after calling setHeader with a different Header");
    }

    @Test
    void setHeader_doesNotAlterMessageSections() {
        // Populate the message with a couple of records in different sections
        Name name = Name.fromConstantString("example.com.");
        Record question = Record.newRecord(name, Type.A, DClass.IN);
        Record answer = Record.newRecord(name, Type.A, DClass.IN);
        message.addRecord(question, Section.QUESTION);
        message.addRecord(answer, Section.ANSWER);
        // Verify initial section sizes
        assertEquals(1, message.getSection(Section.QUESTION).size(), "Question section should contain one record before setHeader");
        assertEquals(1, message.getSection(Section.ANSWER).size(), "Answer section should contain one record before setHeader");
        // Call setHeader and ensure sections remain unchanged
        message.setHeader(header1);
        assertEquals(1, message.getSection(Section.QUESTION).size(), "Question section size should remain unchanged after setHeader");
        assertEquals(1, message.getSection(Section.ANSWER).size(), "Answer section size should remain unchanged after setHeader");
    }

    @Test
    void setHeader_withNullHeader_throwsNPE() {
        // The contract of Message.setHeader does not explicitly allow null,
        // but the underlying implementation simply assigns the field.
        // This test documents the current behaviour (a NullPointerException
        // when trying to use the header later).
        assertThrows(NullPointerException.class, () -> {
            message.setHeader(null);
            // Accessing the header should now throw NPE
            message.getHeader().getID();
        });
    }

    /**
     * Verify that a freshly created Header object is stored correctly and can be
     * retrieved via {@link Message#getHeader()}.
     */
    @Test
    void setHeader_storesFreshHeaderInstance() {
        // uses default constructor
        Header fresh = new Header();
        message.setHeader(fresh);
        assertSame(fresh, message.getHeader(), "The Header instance passed to setHeader should be returned by getHeader");
    }

    /**
     * Ensure that passing {@code null} to {@code setHeader} clears the internal
     * header field and {@link Message#getHeader()} returns {@code null}.
     */
    @Test
    void setHeader_nullClearsHeader() {
        // Initialise with a non‑null header first (the default constructor already does)
        assertNotNull(message.getHeader(), "Precondition: header should be non‑null");
        // Now set to null
        message.setHeader(null);
        assertNull(message.getHeader(), "After setting a null header, getHeader() must return null");
    }

    /**
     * Test that calling {@code setHeader} twice replaces the previous Header with
     * the most recently supplied one.
     */
    @Test
    void setHeader_secondCallOverridesFirst() {
        Header first = new Header(1111);
        Header second = new Header(2222);
        message.setHeader(first);
        assertSame(first, message.getHeader(), "First header should be stored after first setHeader call");
        message.setHeader(second);
        assertSame(second, message.getHeader(), "Second header should replace the first one");
        assertNotSame(first, message.getHeader(), "The earlier Header instance must no longer be referenced");
    }

    /**
     * Confirm that {@code setHeader} stores a reference to the supplied Header
     * object, so later modifications of that Header are visible through the
     * Message.
     */
    @Test
    void setHeader_keepsReferenceAndReflectsExternalModifications() {
        // default ID, Rcode = 0
        Header mutable = new Header();
        // change state before setting
        mutable.setRcode(2);
        message.setHeader(mutable);
        assertEquals(2, message.getHeader().getRcode(), "Rcode should reflect the value set on the Header before setHeader");
        // Modify the Header after it has been stored in the Message
        mutable.setRcode(5);
        assertEquals(5, message.getHeader().getRcode(), "Changes to the Header after setHeader must be visible via getHeader");
    }

    @ParameterizedTest
    @MethodSource("headerScenarios")
    void setHeader_parameterised(HeaderScenario scenario) {
        scenario.apply(message);
    }
}
