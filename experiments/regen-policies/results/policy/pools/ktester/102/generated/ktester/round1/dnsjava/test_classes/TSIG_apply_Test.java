    /**
     * Group: apply(Message, TSIGRecord) - Existing TSIG with Non‑null Old Record (different key)
     */
    @Test
    void applyUsesOldRecordKeyWhenDifferentFromExisting() throws Exception {
        // Message with an existing TSIG (key "example.")
        Record q = Record.newRecord(Name.fromString("c.example."), Type.A, DClass.IN);
        Message msg = Message.newQuery(q);
        tsig.apply(msg, null);
        TSIGRecord existing = msg.getTSIG();
        assertNotNull(existing);
        // Create a second TSIG instance with a different key (keyB)
        // "abcdefghijklmnop"
        SecretKey keyB = new SecretKeySpec(base64.fromString("YWJjZGVmZ2hpamtsbW5vcA=="), "HmacSHA256");
        TSIG tsigB = new TSIG(TSIG.HMAC_SHA256, Name.fromString("keyB."), keyB, FIXED_CLOCK);
        // Generate an old record using tsigB (different key)
        Message dummy = Message.newQuery(q);
        tsigB.apply(dummy, null);
        TSIGRecord oldFromB = dummy.getTSIG();
        // Apply using the old record from keyB
        tsig.apply(msg, oldFromB);
        TSIGRecord after = msg.getTSIG();
        assertNotNull(after);
        assertEquals(Name.fromString("keyB."), after.getName(), "The new TSIG should use the key name from the supplied old record");
    }

    /**
     * Group: apply(Message, TSIGRecord) - Old Record using HMAC‑MD5 algorithm
     */
    @Test
    void applySupportsLegacyHmacMd5Algorithm() throws Exception {
        // Build an old record that uses HMAC‑MD5
        Record q = Record.newRecord(Name.fromString("d.example."), Type.A, DClass.IN);
        Message req = Message.newQuery(q);
        // Use a TSIG instance configured with HMAC‑MD5 algorithm
        SecretKey md5Key = new SecretKeySpec(base64.fromString(B64_KEY), "HmacMD5");
        TSIG tsigMd5 = new TSIG(TSIG.HMAC_MD5, Name.fromString("example."), md5Key, FIXED_CLOCK);
        tsigMd5.apply(req, null);
        TSIGRecord oldMd5 = req.getTSIG();
        Message msg = Message.newQuery(q);
        // tsig (SHA256) should accept the old record's algorithm
        tsig.apply(msg, oldMd5);
        TSIGRecord newRec = msg.getTSIG();
        assertNotNull(newRec);
        assertEquals(TSIG.HMAC_MD5, oldMd5.getAlgorithm(), "Old record must retain HMAC‑MD5 algorithm");
        assertEquals(TSIG.HMAC_SHA256, newRec.getAlgorithm(), "Generated TSIG uses default algorithm (SHA256)");
    }

