package org.xbill.DNS;

import static org.junit.jupiter.api.Assertions.*;
import java.io.IOException;
import org.junit.jupiter.api.*;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.junit.jupiter.MockitoExtension;
import java.time.Duration;
import java.time.Instant;
import java.util.Arrays;
import lombok.extern.slf4j.Slf4j;

@ExtendWith(MockitoExtension.class)
class TSIG_verify_Test {

    /**
     * TSIG key used for signing and verification.
     */
    private TSIG tsigKey;

    /**
     * Original signed query message.
     */
    private Message signedQuery;

    /**
     * Wire‑format representation of {@link #signedQuery}.
     */
    private byte[] signedWire;

    /**
     * The TSIG record generated by {@link Message#setTSIG(TSIG)} on {@link #signedQuery}.
     */
    private TSIGRecord generatedTSIG;

    @BeforeEach
    void setupBeforeEach() throws IOException {
        // Create a deterministic TSIG key (algorithm HMAC‑SHA256, name "example.", key "12345678").
        tsigKey = new TSIG(TSIG.HMAC_SHA256, "example.", "12345678");
        // Build a simple DNS query (A record for www.example.).
        Record question = Record.newRecord(Name.fromString("www.example."), Type.A, DClass.IN);
        signedQuery = Message.newQuery(question);
        // Attach the TSIG to the query – this signs the message.
        signedQuery.setTSIG(tsigKey);
        // Serialize the signed message to wire format (max size 512 bytes).
        signedWire = signedQuery.toWire(512);
        // Keep a reference to the generated TSIG record for the “requestTSIG” argument.
        generatedTSIG = signedQuery.getGeneratedTSIG();
        assertNotNull(generatedTSIG, "TSIG record should have been generated by setTSIG");
    }

    /**
     * Verify that a correctly signed message is accepted (returns NOERROR).
     */
    @Test
    void verifyValidSignature() throws IOException {
        // Parse the wire‑format back into a Message instance.
        Message parsed = new Message(signedWire);
        // Perform verification – we pass the original request TSIG (generatedTSIG) as required.
        int result = tsigKey.verify(parsed, signedWire, generatedTSIG);
        assertEquals(Rcode.NOERROR, result, "Valid TSIG should verify with NOERROR");
        assertTrue(parsed.isVerified(), "Message should be marked as verified after successful check");
        assertTrue(parsed.isSigned(), "Message should still be marked as signed");
    }

    /**
     * Verify that a tampered message fails verification (result is not NOERROR).
     */
    @Test
    void verifyCorruptedMessageFails() throws IOException {
        // Corrupt a single byte somewhere after the DNS header (e.g., byte 30).
        byte[] corrupted = signedWire.clone();
        // flip bits to break the MAC
        corrupted[30] ^= (byte) 0xFF;
        Message parsed = new Message(corrupted);
        int result = tsigKey.verify(parsed, corrupted, generatedTSIG);
        assertNotEquals(Rcode.NOERROR, result, "Corrupted TSIG should not verify – expected an error code");
        // The Message implementation does not automatically clear the verified flag on error,
        // but the verification result itself signals failure.
    }

    /**
     * Verify that verification works when the requestTSIG argument is {@code null}.
     */
    @Test
    void verifyWithNullRequestTSIG() throws IOException {
        Message parsed = new Message(signedWire);
        int result = tsigKey.verify(parsed, signedWire, null);
        assertEquals(Rcode.NOERROR, result, "Verification should succeed even when requestTSIG is null");
        assertTrue(parsed.isVerified(), "Message should be marked as verified");
    }

    /**
     * Verify that using a different TSIG key results in a verification error.
     */
    @Test
    void verifyWithWrongKeyFails() throws IOException {
        // Create a second TSIG instance with a different secret.
        TSIG wrongKey = new TSIG(TSIG.HMAC_SHA256, "example.", "deadbeef");
        Message parsed = new Message(signedWire);
        int result = wrongKey.verify(parsed, signedWire, generatedTSIG);
        assertNotEquals(Rcode.NOERROR, result, "Verification with a mismatched key should fail");
    }

    /**
     * Calling verify with a {@code null} Message should throw {@link NullPointerException}.
     */
    @Test
    void testVerify_NullMessage() {
        byte[] bytes = new byte[] { 0x00, 0x01, 0x02 };
        assertThrows(NullPointerException.class, () -> tsigKey.verify(null, bytes, generatedTSIG), "Null Message should cause NullPointerException");
    }

    /**
     * Passing a {@code null} byte array should cause {@link NullPointerException}.
     */
    @Test
    void testVerify_NullMessageBytes() throws IOException {
        // a valid Message instance
        Message msg = new Message(signedWire);
        assertThrows(NullPointerException.class, () -> tsigKey.verify(msg, null, generatedTSIG), "Null messageBytes should cause NullPointerException");
    }

    /**
     * A {@code null} TSIGRecord argument should raise {@link NullPointerException}.
     */
    @Test
    void testVerify_NullTSIGRecord() throws IOException {
        Message msg = new Message(signedWire);
        byte[] bytes = new byte[] { 0x00, 0x01, 0x02 };
        assertThrows(NullPointerException.class, () -> tsigKey.verify(msg, bytes, null), "Null TSIGRecord should cause NullPointerException");
    }

    /**
     * Unsupported algorithm name should result in {@link IllegalArgumentException}.
     */
    @Test
    void testVerify_UnsupportedAlgorithm() throws IOException {
        // Build a TSIGRecord whose algorithm name is unknown to the TSIG implementation.
        Name keyName = Name.fromString("example.");
        Name unknownAlg = Name.fromString("UNKNOWN-ALG.");
        TSIGRecord badAlgRecord = new TSIGRecord(// name
        keyName, DClass.IN, // ttl (ignored for verification)
        0, // algorithm
        unknownAlg, // timeSigned
        Instant.now().getEpochSecond(), (int) TSIG.FUDGE.getSeconds(), // dummy MAC (non‑empty)
        new byte[] { 0x01, 0x02 }, // originalId
        0, Rcode.NOERROR, // other data
        new byte[0]);
        Message msg = new Message(signedWire);
        assertThrows(IllegalArgumentException.class, () -> tsigKey.verify(msg, signedWire, badAlgRecord), "Unsupported algorithm should cause IllegalArgumentException");
    }

    /**
     * A TSIGRecord with a {@code null} key name should cause {@link NullPointerException}.
     */
    @Test
    void testVerify_NullKeyNameInTSIGRecord() throws IOException {
        // Construct a TSIGRecord with a null name.
        Name alg = TSIG.HMAC_SHA256;
        TSIGRecord nullNameRecord = new TSIGRecord(// key name is null
        null, DClass.IN, 0, alg, Instant.now().getEpochSecond(), (int) TSIG.FUDGE.getSeconds(), new byte[] { 0x01, 0x02 }, 0, Rcode.NOERROR, new byte[0]);
        Message msg = new Message(signedWire);
        assertThrows(NullPointerException.class, () -> tsigKey.verify(msg, signedWire, nullNameRecord), "Null key name in TSIGRecord should cause NullPointerException");
    }

    /**
     * Empty (zero‑length) MAC in the TSIGRecord should trigger {@link IllegalArgumentException}.
     */
    @Test
    void testVerify_EmptySignatureInTSIGRecord() throws IOException {
        Name keyName = Name.fromString("example.");
        TSIGRecord emptyMacRecord = new TSIGRecord(keyName, DClass.IN, 0, TSIG.HMAC_SHA256, Instant.now().getEpochSecond(), (int) TSIG.FUDGE.getSeconds(), // empty MAC
        new byte[0], 0, Rcode.NOERROR, new byte[0]);
        Message msg = new Message(signedWire);
        assertThrows(IllegalArgumentException.class, () -> tsigKey.verify(msg, signedWire, emptyMacRecord), "Empty MAC should cause IllegalArgumentException");
    }

    /**
     * Message byte array that is too short to contain a DNS header should cause {@link IllegalArgumentException}.
     */
    @Test
    void testVerify_InvalidMessageBytesLength() {
        // A single‑byte array – far shorter than the required 12‑byte DNS header.
        byte[] shortBytes = new byte[] { 0x00 };
        // Build a minimal but valid TSIGRecord (the MAC can be dummy because verification will fail earlier).
        Name keyName = Name.fromString("example.");
        TSIGRecord dummyRecord = new TSIGRecord(keyName, DClass.IN, 0, TSIG.HMAC_SHA256, Instant.now().getEpochSecond(), (int) TSIG.FUDGE.getSeconds(), new byte[] { 0x01 }, 0, Rcode.NOERROR, new byte[0]);
        // empty message – content does not matter for this test
        Message msg = new Message();
        assertThrows(IllegalArgumentException.class, () -> tsigKey.verify(msg, shortBytes, dummyRecord), "Too‑short messageBytes should cause IllegalArgumentException");
    }
}
